-- FINDING COUNTRY WITH LARGE NO. OF INVOICES
SELECT BILLING_COUNTRY, COUNT(*) AS TOTAL_NVOICES FROM INVOICE
GROUP BY BILLING_COUNTRY
ORDER BY TOTAL_NVOICES DESC
LIMIT 1


-- TOP 3 VALUES OF TOTAL INVOICES
SELECT TOTAL FROM INVOICE
ORDER BY TOTAL DESC
LIMIT 3


-- WHICH TOP 3 CITY HAS THE BEST CUSTOMER AS PER SUM OF INVOICES
SELECT BILLING_CITY AS CITY, SUM(TOTAL) AS TOTAL_NVOICES FROM INVOICE
GROUP BY BILLING_CITY
ORDER BY TOTAL_NVOICES DESC
LIMIT 3


-- WHICH TOP 3 CUSTOMER HAS SPENT MORE MONEY
SELECT FIRST_NAME||' '||LAST_NAME AS FULL_NAME,SUM(TOTAL) AS MONEY_SPENT FROM CUSTOMER AS C
JOIN INVOICE I ON C.CUSTOMER_ID=I.CUSTOMER_ID
GROUP BY FULL_NAME
ORDER BY MONEY_SPENT DESC
LIMIT 3


-- QUERY TO RETURN THE EMAIL, FIRST NAME, LAST NAME, & GENRE OF ALL ROCK MUSIC
-- LISTENERS. RETURN YOUR LIST ORDERED ALPHABETICALLY BY EMAIL STARTING WITH A
SELECT EMAIL,FIRST_NAME,LAST_NAME FROM CUSTOMER AS C
JOIN INVOICE I ON C.CUSTOMER_ID=I.CUSTOMER_ID
JOIN INVOICE_LINE IL ON I.INVOICE_ID=IL.INVOICE_ID
WHERE TRACK_ID IN(
SELECT TRACK_ID FROM TRACK AS T
JOIN GENRE G ON T.GENRE_ID = G.GENRE_ID
WHERE G.NAME='ROCK'
)
ORDER BY EMAIL;


-- LET'S INVITE THE ARTISTS WHO HAVE WRITTEN THE MOST ROCK MUSIC IN OUR DATASET. WRITE A
-- QUERY THAT RETURNS THE ARTIST NAME AND TOTAL TRACK COUNT OF THE TOP 10 ROCK BANDS
SELECT A.ARTIST_ID,A.NAME,COUNT(A.ARTIST_ID) AS SONGS FROM TRACK T
JOIN ALBUM M ON T.ALBUM_ID=M.ALBUM_ID
JOIN ARTIST A ON M.ARTIST_ID=A.ARTIST_ID
JOIN GENRE G ON T.GENRE_ID=G.GENRE_ID
WHERE G.NAME = 'ROCK'
GROUP BY A.ARTIST_ID
ORDER BY SONGS DESC
LIMIT 10


-- RETURN ALL THE TRACK NAMES THAT HAVE A SONG LENGTH LONGER THAN THE AVERAGE SONG LENGTH.
-- RETURN THE NAME AND MILLISECONDS FOR EACH TRACK. ORDER BY THE SONG LENGTH WITH THE
-- LONGEST SONGS LISTED FIRST
SELECT T.NAME,T.MILLISECONDS FROM TRACK AS T
WHERE T.MILLISECONDS > (SELECT AVG(MILLISECONDS) FROM TRACK)
ORDER BY T.MILLISECONDS DESC
LIMIT 10


-- QUERY FOR MONEY SPENT BY CUSTOMERS ON ARTIST
SELECT C.CUSTOMER_ID,C.FIRST_NAME,C.LAST_NAME,A.NAME AS ARTIST,
SUM(IL.QUANTITY * IL.UNIT_PRICE) AS AMOUNT_SPENT
FROM CUSTOMER C
JOIN INVOICE I
    ON C.CUSTOMER_ID = I.CUSTOMER_ID
JOIN INVOICE_LINE IL
    ON I.INVOICE_ID = IL.INVOICE_ID
JOIN TRACK T
    ON IL.TRACK_ID = T.TRACK_ID
JOIN ALBUM M
    ON T.ALBUM_ID = M.ALBUM_ID
JOIN ARTIST A
    ON M.ARTIST_ID = A.ARTIST_ID
GROUP BY
    C.CUSTOMER_ID,
    A.ARTIST_ID
ORDER BY AMOUNT_SPENT DESC;



-- QUERY THAT RETURNS EACH COUNTRY ALONG WITH THE TOP GENRE. FOR COUNTRIES WHERE THE MAXIMUM
-- NUMBER OF PURCHASES IS SHARED RETURN ALL GENRES
WITH POP AS (
    SELECT
        C.COUNTRY,
        G.NAME,
        COUNT(IL.QUANTITY) AS PURCHASES,
        G.GENRE_ID,
        DENSE_RANK() OVER (
            PARTITION BY C.COUNTRY
            ORDER BY COUNT(IL.QUANTITY) DESC
        ) AS ROW_NO
    FROM CUSTOMER C
    JOIN INVOICE I
        ON C.CUSTOMER_ID = I.CUSTOMER_ID
    JOIN INVOICE_LINE IL
        ON I.INVOICE_ID = IL.INVOICE_ID
    JOIN TRACK T
        ON IL.TRACK_ID = T.TRACK_ID
    JOIN GENRE G
        ON T.GENRE_ID = G.GENRE_ID
    GROUP BY
        C.COUNTRY,
        G.GENRE_ID
)
SELECT *
FROM POP
WHERE ROW_NO = 1



-- QUERY THAT RETURNS THE COUNTRY ALONG WITH THE TOP CUSTOMER AND HOW
-- MUCH THEY SPENT. FOR COUNTRIES WHERE THE TOP AMOUNT SPENT IS SHARED, PROVIDE ALL
-- CUSTOMERS WHO SPENT THIS AMOUNT
WITH CWS AS (
    SELECT
        I.BILLING_COUNTRY,C.CUSTOMER_ID,
        C.FIRST_NAME,C.LAST_NAME,
        SUM(TOTAL) AS TOTAL_SPENT,
        DENSE_RANK() OVER (
            PARTITION BY I.BILLING_COUNTRY
            ORDER BY SUM(TOTAL) DESC
        ) AS ROW_NO
    FROM CUSTOMER C
    JOIN INVOICE I
        ON C.CUSTOMER_ID = I.CUSTOMER_ID
    GROUP BY
        I.BILLING_COUNTRY,
        C.CUSTOMER_ID
    ORDER BY 1 ASC
)
SELECT *
FROM CWS
WHERE ROW_NO = 1